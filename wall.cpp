{
    QPoint gridPos = worldToGrid(x, y);

    // 检查边界
    if (gridPos.x() < 0 || gridPos.x() >= MAZE_COLS ||
        gridPos.y() < 0 || gridPos.y() >= MAZE_ROWS) {
        return true;  // 边界外视为墙
    }

    return mazeData[gridPos.y()][gridPos.x()] == 1;
}

int Wall::getCellValue(int row, int col) const
{
    if (row >= 0 && row < MAZE_ROWS && col >= 0 && col < MAZE_COLS) {
        return mazeData[row][col];
    }
    return 1;  // 边界外返回墙
}

const int (*Wall::getMazeData() const)[MAZE_COLS]
{
    return mazeData;
}

int Wall::getRows() const
{
    return MAZE_ROWS;
}

int Wall::getCols() const
{
    return MAZE_COLS;
}

int Wall::getCellSize() const
{
    return CELL_SIZE;
}

int Wall::getDamage() const
{
    return wallDamage;
}

void Wall::setDamage(int damage)
{
    if (damage >= 0) {
        wallDamage = damage;
    }
}

QPoint Wall::worldToGrid(float worldX, float worldY) const
{
    int gridX = static_cast<int>(worldX) / CELL_SIZE;
    int gridY = static_cast<int>(worldY) / CELL_SIZE;
    return QPoint(gridX, gridY);
}

QVector<QRectF> Wall::getWallRects() const
{
    QVector<QRectF> rects;
    for (int row = 0; row < MAZE_ROWS; row++) {
        for (int col = 0; col < MAZE_COLS; col++) {
            if (mazeData[row][col] == 1) {
                rects.append(QRectF(col * CELL_SIZE, row * CELL_SIZE, CELL_SIZE, CELL_SIZE));
            }
        }
    }
    return rects;
}
