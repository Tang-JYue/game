bool Wall::checkCollision(const QRectF& rect) const
{
    // 检查矩形的四个角
    if (isPointInWall(rect.left(), rect.top()) ||
        isPointInWall(rect.right(), rect.top()) ||
        isPointInWall(rect.left(), rect.bottom()) ||
        isPointInWall(rect.right(), rect.bottom())) {
        return true;
    }

    // 检查矩形四条边的中点（更精确的检测）
    if (isPointInWall(rect.center().x(), rect.top()) ||
        isPointInWall(rect.center().x(), rect.bottom()) ||
        isPointInWall(rect.left(), rect.center().y()) ||
        isPointInWall(rect.right(), rect.center().y())) {
        return true;
    }

    return false;
}

